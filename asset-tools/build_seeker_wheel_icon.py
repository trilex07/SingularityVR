"""Generate the embedded Seeker wheel texture from the remaster icon master."""

import argparse
import io
from PIL import Image, ImageDraw, ImageFont

from build_detailed_weapon_icons import ROOT, SOURCE, SPRITES, make_sprite


SIDE = 128
MASTER = SOURCE / "weapon_icon_seeker_master.png"
SPRITE = SPRITES / "weapon_icon_seeker.png"
HEADER = ROOT / "spikes/view_matrix/seeker_wheel_pixels.generated.h"
PREVIEW = ROOT / "docs/previews/ui_remaster/seeker_weapon_icon.png"


def png(image):
    stream = io.BytesIO()
    image.save(stream, format="PNG", optimize=True)
    return stream.getvalue()


def embed(sprite):
    # Straight alpha and luminance; RGB follows the other remaster glyphs.
    # A zero (offset, length) ends the list. Translucent edges keep their RGB.
    data = []
    rgba = list(sprite.get_flattened_data())
    for y in range(SIDE):
        row = rgba[y * SIDE:(y + 1) * SIDE]
        present = [x for x, p in enumerate(row) if p[3]]
        if not present:
            continue
        left, right = min(present), max(present) + 1
        data.extend((y * SIDE + left, right - left))
        data.extend((a << 8) | (g - 2 if a else 173) for _, g, _, a in row[left:right])
    data.extend((0, 0))
    lines = ["    " + ", ".join(f"0x{v:04x}" for v in data[i:i + 12]) + ","
             for i in range(0, len(data), 12)]
    head = (
        "#pragma once\n"
        "// Generated by asset-tools/build_seeker_wheel_icon.py.\n"
        "#include <cstdint>\n\n"
        "namespace seekericon {\n"
        f"inline constexpr unsigned TextureSide = {SIDE};\n"
        "inline constexpr std::uint16_t TextureSpans[] = {\n"
    )
    return (head + "\n".join(lines) + "\n};\n}\n").encode("ascii")


def preview(sprite):
    sheet = Image.new("RGBA", (810, 215), "#151c22")
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.load_default(size=16)
    names = ("centurion", "valkyrie", "spikeshot", "kasimov", "seeker")
    for i, name in enumerate(names):
        x = 13 + 160 * i
        draw.text((x, 12), name.upper(), fill="#ddd8c4", font=font)
        draw.rounded_rectangle((x, 40, x + 143, 184), radius=15, fill="#292f33",
                               outline="#ec9b41" if name == "seeker" else "#5e6e76", width=2)
        current = sprite if name == "seeker" else Image.open(SPRITES / f"weapon_icon_{name}.png")
        sheet.alpha_composite(current.convert("RGBA").resize((128, 128), Image.Resampling.LANCZOS),
                              (x + 8, 48))
    return sheet


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without editing")
    args = parser.parse_args()
    sprite = make_sprite(MASTER, SIDE, SIDE, content_height=36)
    for path, payload in ((SPRITE, png(sprite)), (HEADER, embed(sprite)), (PREVIEW, png(preview(sprite)))):
        if args.check:
            current = path.read_bytes()
            if path == HEADER:
                current = current.replace(b"\r\n", b"\n")
            if current != payload:
                raise SystemExit(f"outdated: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(payload)


if __name__ == "__main__":
    main()
