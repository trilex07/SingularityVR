"""Generate Seeker bridge registrations and replacement SHA pins from private evidence."""
import argparse
import hashlib
import json
from pathlib import Path

def main(root, repo):
    receipt=json.loads((root/'native_identity/identity.json').read_text())
    rows=[];pins=[]
    for suffix in ('d','n'):
        name='ar_steerable_'+suffix;r=receipt[name]
        raw=(root/'native_identity'/(name+'.mip0.bin')).read_bytes()
        h=0xcbf29ce484222325
        for b in raw:h=((h^b)*0x100000001b3)&0xffffffffffffffff
        if f'{h:016X}'!=r['fnv1a64'] or hashlib.sha256(raw).hexdigest()!=r['mip0_sha256']:raise ValueError('identity drift')
        rows.append(f'    {{ "{name}", 2048u, 1024u, D3DFMT_{r["format"][3:]}, {h}ULL, "AR_Steerable_{suffix}.dds", "weapons" }},')
        pins.append(hashlib.sha256((root/'final_handoff/native_textures'/f'AR_Steerable_{suffix}.dds').read_bytes()).hexdigest())
    target=repo/'spikes/texture_cache/targets_generated.h'
    text=target.read_text();text='\n'.join(line for line in text.splitlines() if '"ar_steerable_' not in line)+'\n'
    text=text.replace('static const Target kTargets[] = {','static const Target kTargets[] = {\n'+'\n'.join(rows))
    target.write_text(text)
    (repo/'spikes/texture_cache/seeker_targets_generated.h').write_text(
        '// Generated by tools/seeker/register_native_targets.py; no game pixels.\n'
        'static const char* seekerFiles[]={"vr-assets/reload/seeker/AR_Steerable_d.dds","vr-assets/reload/seeker/AR_Steerable_n.dds"};\n'
        'static const char* seekerSha[]={'+','.join('"'+s+'"' for s in pins)+'};\n')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--private',type=Path,required=True);p.add_argument('--repo',type=Path,default=Path('.'))
    a=p.parse_args();main(a.private,a.repo)
