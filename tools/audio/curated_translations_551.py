def get_curated_pl(text_en, fallback_pl):
    en_clean = text_en.strip()
    if en_clean in CURATED_MAPPING:
        return CURATED_MAPPING[en_clean]
    t = fallback_pl.strip().lstrip('- ').lstrip('> ').strip()
    if ' - ' in t:
        parts = t.split(' - ')
        t = parts[0].strip()
    return t
